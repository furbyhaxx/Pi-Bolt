#!/usr/bin/env node

import { createPublicKey } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
let configFile = join(root, "fork.json");
let outputFile = join(root, "packages/coding-agent/src/pi-bolt-fork.generated.ts");
let check = false;
let json = false;
const args = process.argv.slice(2);

for (let i = 0; i < args.length; i++) {
	const arg = args[i];
	if (arg === "--check") check = true;
	else if (arg === "--json") json = true;
	else if (arg === "--config" || arg === "--output") {
		const value = args[++i];
		if (!value || value.startsWith("--")) throw new Error(`${arg} requires a path`);
		if (arg === "--config") configFile = resolve(value);
		else outputFile = resolve(value);
	} else throw new Error(`Unknown argument: ${arg}`);
}
if (check && json) throw new Error("--check and --json cannot be combined");

const config = JSON.parse(readFileSync(configFile, "utf8"));
const repoPattern = /^[a-zA-Z0-9][a-zA-Z0-9-]*\/[a-zA-Z0-9_.-]+$/;
if (typeof config.repository !== "string" || !repoPattern.test(config.repository)) {
	throw new Error("repository must be a GitHub owner/repository");
}
if (typeof config.upstreamRepository !== "string" || !repoPattern.test(config.upstreamRepository)) {
	throw new Error("upstreamRepository must be a GitHub owner/repository");
}
if (typeof config.upstreamBranch !== "string" || !/^[a-zA-Z0-9._/-]+$/.test(config.upstreamBranch)) {
	throw new Error("upstreamBranch must be a Git branch name");
}
if (typeof config.tagPrefix !== "string" || !/^[a-zA-Z0-9._-]+$/.test(config.tagPrefix)) {
	throw new Error("tagPrefix must contain only letters, digits, dots, underscores or hyphens");
}
if (typeof config.publicKeyFile !== "string" || !config.publicKeyFile) {
	throw new Error("publicKeyFile must be a path relative to the configuration");
}
const releasePublicKey = readFileSync(resolve(dirname(configFile), config.publicKeyFile), "utf8");
if (
	!/^-----BEGIN PUBLIC KEY-----\r?\n[A-Za-z0-9+/=\r\n]+-----END PUBLIC KEY-----\r?\n?$/.test(releasePublicKey) ||
	createPublicKey(releasePublicKey).asymmetricKeyType !== "ed25519"
) {
	throw new Error("publicKeyFile must contain an Ed25519 public key in PEM format");
}

const repositoryUrl = `https://github.com/${config.repository}`;
const releasesUrl = `${repositoryUrl}/releases`;
const releasesApi = `https://api.github.com/repos/${config.repository}/releases`;
const identity = {
	repository: config.repository,
	upstreamRepository: config.upstreamRepository,
	upstreamBranch: config.upstreamBranch,
	tagPrefix: config.tagPrefix,
	publicKeyFile: config.publicKeyFile,
	releasePublicKey,
	repositoryUrl,
	upstreamUrl: `https://github.com/${config.upstreamRepository}`,
	releasesUrl,
	latestReleaseUrl: `${releasesUrl}/latest`,
	releasesFeed: `${releasesUrl}.atom`,
	latestReleaseApi: `${releasesApi}/latest`,
	releasesApi: `${releasesApi}?per_page=30`,
	releaseDownloadBase: `${releasesUrl}/download`,
	installShUrl: `${releasesUrl}/latest/download/install.sh`,
	installPs1Url: `${releasesUrl}/latest/download/install.ps1`,
};

if (json) {
	process.stdout.write(`${JSON.stringify(identity, null, 2)}\n`);
} else {
	const generated = [
		"// Generated by scripts/generate-fork-config.mjs; edit fork.json or the public key instead.",
		"export const PIBOLT_FORK = {",
		...Object.entries(identity).map(([key, value]) => {
			const encoded = JSON.stringify(value);
			const property = `${key}: ${encoded},`;
			return property.length + 3 > 120 ? `\t${key}:\n\t\t${encoded},` : `\t${property}`;
		}),
		"} as const;",
		"",
	].join("\n");
	if (check) {
		if (!existsSync(outputFile) || readFileSync(outputFile, "utf8") !== generated) {
			console.error(`${outputFile} is out of date; run node scripts/generate-fork-config.mjs`);
			process.exitCode = 1;
		}
	} else {
		writeFileSync(outputFile, generated);
	}
}
